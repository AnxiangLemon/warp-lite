/// Translate a settings UI string when building Warp Lite; otherwise pass through.
pub fn tr(text: impl AsRef<str>) -> String {
    let text = text.as_ref();
    if cfg!(feature = "warp_lite") {
        TRANSLATIONS
            .get(text)
            .copied()
            .unwrap_or(text)
            .to_owned()
    } else {
        text.to_owned()
    }
}

pub fn tr_cow(text: impl Into<Cow<'static, str>>) -> Cow<'static, str> {
    let text = text.into();
    if !cfg!(feature = "warp_lite") {
        return text;
    }
    let key: &str = text.as_ref();
    match TRANSLATIONS.get(key) {
        Some(&zh) => Cow::Borrowed(zh),
        None => text,
    }
}
